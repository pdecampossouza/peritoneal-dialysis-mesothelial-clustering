"""
prepare_dataset_overview.py

This script:

1. Loads "data_patient.xlsx" (patient-level information).
2. Loads "data_image.xlsx" (image-level information generated by build_data_image.py).
3. Checks basic consistency between both tables.
4. Merges them into a single table with one row per image, including patient info.
5. Saves the merged table as "data_image_with_patient.xlsx".
6. Prints a human-readable summary in the terminal.

The goal is to have a clean starting point for later feature extraction
and machine learning analysis.
"""

from pathlib import Path
import pandas as pd


def main():
    print("=" * 70)
    print("PREPARE DATASET OVERVIEW – START")
    print("=" * 70)

    # ------------------------------------------------------------------
    # 1. Define project root and file paths
    # ------------------------------------------------------------------
    root = Path(__file__).resolve().parent
    print(f"[INFO] Project root folder: {root}")

    path_patient = root / "data_patient.xlsx"
    path_image = root / "data_image.xlsx"

    # Check that both Excel files exist
    if not path_patient.exists():
        print(f"[ERROR] File not found: {path_patient}")
        return

    if not path_image.exists():
        print(f"[ERROR] File not found: {path_image}")
        return

    print(f"[INFO] Found patient file: {path_patient.name}")
    print(f"[INFO] Found image file:   {path_image.name}")

    # ------------------------------------------------------------------
    # 2. Load the Excel files
    # ------------------------------------------------------------------
    print("\n[STEP] Loading Excel files...\n")
    df_patient = pd.read_excel(path_patient)
    df_image = pd.read_excel(path_image)

    print(
        f"[INFO] Patients table: {df_patient.shape[0]} rows, {df_patient.shape[1]} columns."
    )
    print(
        f"[INFO] Images table:   {df_image.shape[0]} rows, {df_image.shape[1]} columns."
    )

    # ------------------------------------------------------------------
    # 3. Basic checks on IDs
    # ------------------------------------------------------------------
    print("\n[STEP] Checking patient IDs...\n")

    patients_from_patient = set(df_patient["patient_id"].unique())
    patients_from_image = set(df_image["patient_id"].unique())

    print(f"[INFO] Unique patient IDs in data_patient: {sorted(patients_from_patient)}")
    print(f"[INFO] Unique patient IDs in data_image:   {sorted(patients_from_image)}")

    missing_in_patient = patients_from_image - patients_from_patient
    missing_in_image = patients_from_patient - patients_from_image

    if missing_in_patient:
        print(
            "[WARNING] Some patient IDs appear in data_image but not in data_patient:"
        )
        print(f"          {sorted(missing_in_patient)}")
    else:
        print("[OK] All patient IDs in data_image are present in data_patient.")

    if missing_in_image:
        print(
            "[WARNING] Some patient IDs appear in data_patient but not in data_image:"
        )
        print(f"          {sorted(missing_in_image)}")
    else:
        print("[OK] All patient IDs in data_patient are present in data_image.")

    # ------------------------------------------------------------------
    # 4. Check images per patient and per well
    # ------------------------------------------------------------------
    print("\n[STEP] Checking number of images per patient and per well...\n")

    # Expected: 5 wells × 5 zones × 2 modes = 50 images per patient
    expected_per_patient = 5 * 5 * 2

    images_per_patient = df_image.groupby("patient_id")["filename"].count()

    for pid, count in images_per_patient.items():
        if count == expected_per_patient:
            print(f"[OK] Patient {pid}: {count} images (as expected).")
        else:
            print(
                f"[WARNING] Patient {pid}: {count} images "
                f"(expected {expected_per_patient})."
            )

    # Optional: check wells and zones
    print("\n[STEP] Quick check of wells and zones per patient...\n")

    for pid in sorted(patients_from_image):
        df_pid = df_image[df_image["patient_id"] == pid]
        wells = sorted(df_pid["well"].unique())
        zones = sorted(df_pid["zone"].unique())
        print(f"  -> Patient {pid}: wells = {wells}, zones = {zones}")

    # ------------------------------------------------------------------
    # 5. Merge patient info into image table
    # ------------------------------------------------------------------
    print("\n[STEP] Merging patient data into the image table...\n")

    # We merge on the 'patient_id' column
    df_merged = df_image.merge(df_patient, on="patient_id", how="left")

    # Check if some images have missing patient info
    missing_info = df_merged["time_in_culture_days"].isna().sum()
    if missing_info > 0:
        print(
            f"[WARNING] There are {missing_info} images with missing patient info "
            "(time_in_culture_days is NaN)."
        )
    else:
        print("[OK] No missing patient info after merge.")

    # ------------------------------------------------------------------
    # 6. Save the merged table
    # ------------------------------------------------------------------
    output_path = root / "data_image_with_patient.xlsx"
    df_merged.to_excel(output_path, index=False)

    # ------------------------------------------------------------------
    # 7. Summary
    # ------------------------------------------------------------------
    n_patients = df_patient["patient_id"].nunique()
    n_images = df_image.shape[0]

    print("\n" + "=" * 70)
    print("PREPARE DATASET OVERVIEW – DONE")
    print("=" * 70)
    print(f"[SUMMARY] Number of patients in patient table: {n_patients}")
    print(f"[SUMMARY] Number of images in image table:    {n_images}")
    print(f"[SUMMARY] Merged table saved as:              {output_path}")
    print("=" * 70)


if __name__ == "__main__":
    main()
